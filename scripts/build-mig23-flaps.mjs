import fs from 'node:fs';
const source=JSON.parse(fs.readFileSync('assets/mig23mld/flap-source-shapes.json'));
if(source.referenceSweepDegrees!==72||Object.keys(source.parts).join(',')!=='16,17')throw Error('Unexpected flap source');
const rows=Object.entries(source.parts).map(([id,p])=>({part:+id,parent:+id===16?1:2,nodes:p.nodes,point:p.hingePoint,axis:p.hingeAxis,sign:p.flapSign}));
const text='// Tim Samedov source, CC BY4.0; generated by build-mig23-flaps.mjs.\n// Fitted authored welded hinge, not surveyed MLD geometry.\nexport const FLAP_RIG='+JSON.stringify(rows)+';\n';
const path='web/mig23mld-flap-data.js';
if(process.argv.includes('--check')){if(fs.readFileSync(path,'utf8')!==text)throw Error('Flap rig data is stale');}
else fs.writeFileSync(path,text);
