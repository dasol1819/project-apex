// Rebuild the reviewed fin triangle partition from the restored original GLB.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const scratch=fs.mkdtempSync(path.join(os.tmpdir(),'apex-fin-'));
try{
 const csv=execFileSync(process.execPath,['scripts/export-mig23-fin.mjs'],{cwd:root,maxBuffer:8*1024*1024});
 const input=path.join(scratch,'triangles.csv'),exe=path.join(scratch,'partition');fs.writeFileSync(input,csv);
 execFileSync('c++',['-std=c++17','-O2','-Wall','-Wextra','-Wpedantic','-Werror','scripts/partition-mig23-fin.cpp','-o',exe],{cwd:root,stdio:'inherit'});
 const json=execFileSync(exe,[input],{encoding:'utf8'}),data=JSON.parse(json);
 const js='// Tim Samedov original GLB CC BY 4.0. Generated by scripts/build-mig23-fin.mjs.\nexport const FIN_PARTITION='+JSON.stringify(data)+';\n';
 for(const [file,content] of [['assets/mig23mld/fin-damage-partition.json',json],['web/mig23mld-fin-data.js',js]]){
  const dest=path.join(root,file);
  if(process.argv.includes('--check')){if(fs.readFileSync(dest,'utf8')!==content)throw Error('Stale fin partition: '+file);}
  else fs.writeFileSync(dest,content);
 }
 console.log(JSON.stringify({result:'PASS',check:process.argv.includes('--check'),components:data.components,triangles:data.sourceTriangles+data.attachmentTriangles,nativeShape:data.nativeShape}));
}finally{fs.rmSync(scratch,{recursive:true,force:true});}
