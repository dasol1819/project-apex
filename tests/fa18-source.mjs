import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { createHash } from 'node:crypto';

const webRoot = process.argv[2] || 'web';
const relative = 'assets/fa18/F18_Hornet_optimized.glb';
const data = readFileSync(join(webRoot, relative));
const digest = createHash('sha256').update(data).digest('hex');
const expected = 'e427459761adf590c6704f2c49ca051ba500c6be614a999f084c582b171f8944';
assert.equal(data.length, 21572512, 'F-18 GLB size');
assert.equal(digest, expected, 'F-18 GLB checksum');
assert.equal(data.toString('ascii', 0, 4), 'glTF', 'GLB magic');
assert.equal(data.readUInt32LE(4), 2, 'GLB version');
assert.equal(data.readUInt32LE(8), data.length, 'GLB declared length');
const jsonSize = data.readUInt32LE(12);
assert.equal(data.toString('ascii', 16, 20), 'JSON', 'GLB JSON chunk');
const gltf = JSON.parse(data.toString('utf8', 20, 20 + jsonSize));
assert.equal(gltf.meshes.length, 55, 'Expected authored meshes');
assert.equal(gltf.nodes.length, 67, 'Expected scene nodes');
assert.equal(gltf.materials.length, 12, 'Expected authored materials');
assert.equal(gltf.buffers.length, 1, 'Expected embedded binary buffer');
const binaryHeader = 20 + jsonSize;
assert.equal(data.toString('ascii', binaryHeader + 4, binaryHeader + 8), 'BIN\0', 'GLB binary chunk');
const manifest = JSON.parse(readFileSync(join(webRoot, 'manifest.json'), 'utf8'));
assert.equal(manifest.files[relative], expected, 'Deployment manifest hash');
const credits = readFileSync(join(webRoot, 'assets/fa18/CREDITS.txt'), 'utf8');
assert.match(credits, /ChrisKuhn/);
assert.match(credits, /CC BY/);
const importer = readFileSync(join(webRoot, 'fa18-hornet-import.js'), 'utf8');
assert.match(importer, /F18_Hornet_optimized\.glb/);
const aircraft = readFileSync(join(webRoot, 'aircraft.js'), 'utf8');
assert.match(aircraft, /createFa18fSourceAircraft/);
console.log('F-18 GLB validated:', data.length, 'bytes;', gltf.meshes.length, 'meshes;', gltf.nodes.length, 'nodes');
